import os
import sys
import logging

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

logging.basicConfig(level=logging.INFO, format='%(asctime)s [DOC GEN] %(message)s')








































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































DOCS_DIR = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "docs")

def generate_all_docs():
    """Generates all three documentation sets and saves them to the docs/ directory."""
    from docs.doc_engine import (
        generate_doc1_user_manual,
        generate_doc2_replication_dna,
        generate_doc3_cognitive_architecture
    )
    from knowledge_base.kb import add_entry

    if not os.path.exists(DOCS_DIR):
        os.makedirs(DOCS_DIR)

    # Doc 1: User Manual
    doc1_content = generate_doc1_user_manual()
    doc1_path = os.path.join(DOCS_DIR, "user_manual.md")
    with open(doc1_path, "w") as f:
        f.write(doc1_content)
    logging.info(f"Generated: {doc1_path}")

    # Doc 2: Replication DNA
    doc2_content = generate_doc2_replication_dna()
    doc2_path = os.path.join(DOCS_DIR, "replication_dna.md")
    with open(doc2_path, "w") as f:
        f.write(doc2_content)
    logging.info(f"Generated: {doc2_path}")

    # Doc 3: Cognitive Architecture
    doc3_content = generate_doc3_cognitive_architecture()
    doc3_path = os.path.join(DOCS_DIR, "cognitive_architecture.md")
    with open(doc3_path, "w") as f:
        f.write(doc3_content)
    logging.info(f"Generated: {doc3_path}")
    
    add_entry("Triple-tier documentation generated successfully.", "doc_update", "risk_engine")
    
    return [doc1_path, doc2_path, doc3_path]

if __name__ == "__main__":
    generated_files = generate_all_docs()
    print(f"\nSuccessfully generated {len(generated_files)} documents:")
    for f in generated_files:
        print(f"- {f}")
